using MapRows = std::array<std::string_view, MAX_GRID_Y>;

NibblerStaticMap convertStaticMap(const MapRows &rows)
{
    NibblerStaticMap map = {};

    for (std::size_t y = 0; y < MAX_GRID_Y; ++y) {
        for (std::size_t x = 0; x < MAX_GRID_X; ++x)
            map[y][x] = (rows[y][x] == '1') ? 1 : 0;
    }

    return map;
}

